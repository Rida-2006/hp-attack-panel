const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
let browser
;(async () => {
  browser = await chromium.launch({ headless:true, channel:process.env.BROWSER_CHANNEL || 'msedge' })
  const page = await browser.newPage({ viewport:{ width:1440, height:1100 } })
  const errors=[]; page.on('pageerror',e=>errors.push(e.message))
  await page.goto('http://127.0.0.1:5011', {waitUntil:'domcontentloaded'})
  await page.getByText('Browser QA fixture', {exact:false}).waitFor()
  await page.getByRole('heading',{name:'Attack Panel',exact:true}).waitFor()
  assert.equal(await page.locator('nav').count(),0)
  assert.equal(await page.locator('table').count(),0)
  const request = page.waitForResponse(r => r.url().endsWith('/api/attacks/random') && r.request().method() === 'POST')
  await page.getByRole('button',{name:'Random Attack',exact:true}).click()
  const result = await (await request).json()
  assert.equal(result.http_status, 200)
  assert.equal(result.success, true)
  assert.ok(result.response_body.includes('FULL_RESPONSE_END'))
  await page.locator('.terminal-line .kind-body').waitFor()
  assert.equal(await page.locator('.terminal-line:has(.kind-body) pre').last().textContent(), result.response_body)
  assert.equal(await page.evaluate(() => window.mockResponseExecuted), undefined)
  await page.locator('.terminal-line').getByText(/HTTP 200/).first().waitFor()
  await page.getByRole('button',{name:'Custom Shell',exact:false}).click()
  await page.getByRole('textbox',{name:'Custom Shell command'}).fill('help')
  await page.getByRole('button',{name:'Execute',exact:false}).click()
  await page.locator('.terminal-line').getByText(/This is an allowlisted test console/).waitFor()
  await page.getByRole('textbox',{name:'Custom Shell command'}).fill('whoami')
  await page.getByRole('button',{name:'Execute',exact:false}).click()
  await page.locator('.terminal-line').getByText(/Unsupported command/).waitFor()
  await page.screenshot({path:'tests/artifacts/attack-panel-desktop.png',fullPage:true})
  await page.setViewportSize({width:390,height:844})
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
  await page.screenshot({path:'tests/artifacts/attack-panel-mobile.png',fullPage:true})
  await page.getByRole('button',{name:'Clear view',exact:true}).click()
  await page.getByText('Awaiting execution',{exact:false}).waitFor()
  assert.deepEqual(errors,[])
  await browser.close()
  console.log('Attack Panel browser checks passed: hero launch, full real response, safe text rendering, streaming, custom commands, validation, clear, responsive layout, no SIEM navigation.')
})().catch(async e=>{console.error(e);await browser?.close();process.exitCode=1})
